-- fusion database DDL (spec 2026-09-16 D13, plan decisions 2026-09-18): schema-per-version catalog.
-- ddl_version: 10
--
-- Blocks (applied by import.mts, in this order):
--   @block meta    — schema `meta`: seeds + the single-row active_version pointer
--   @block corpus  — {{S}} = the corpus/registry DDL shared by every version schema AND `customer`
--   @block vendor  — {{V}} = vendor-only data of one delivered version (schema catalog, registries,
--                    layout corpus, enrich store, col_vec)
-- {{S}} / {{V}} are replaced by the importer with the target schema name (e.g. v2026_09). Every
-- statement is idempotent (IF NOT EXISTS) so `customer` survives repeated imports untouched.
--
-- Types: SQLite 384×float32 BLOB → vector(384); JSON-in-text stays text (readers JSON.parse it; jsonb
-- would change the client wire shape — a port-time decision). Registries live ONLY in the version
-- schema (computed over vendor ∪ customer at upgrade time); `customer` = corpus + flex/adf + rules.
-- Vector indexes: NONE yet — exact scan (`ORDER BY embedding <-> $1`) is the baseline at ~100k rows.
-- When an ANN index is wanted it goes right after the two corpus vector tables (same L2 metric as
-- sqlite-vec's default), either pgvector's HNSW or vectorscale's DiskANN (`vectorscale` is installed):
--   CREATE INDEX ... ON {{S}}.report_queries           USING hnsw    (embedding vector_l2_ops);
--   CREATE INDEX ... ON {{S}}.report_queries_vec_multi USING hnsw    (embedding vector_l2_ops);
--   CREATE INDEX ... ON {{S}}.report_queries           USING diskann (embedding vector_l2_ops);
--   CREATE INDEX ... ON {{S}}.report_queries_vec_multi USING diskann (embedding vector_l2_ops);

