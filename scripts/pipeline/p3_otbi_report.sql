-- ============================================================================
-- P3o-c — the two OTBI catalog reports, written by p3_otbi.sh report into data/:
--   -v section=gap        data/otbi_gap_list.md       what an LLM pass would still have to describe
--   -v section=reconcile  data/otbi_reconciliation.md lineage-only / crawl-only / corpus-only items
-- Read-only over work.otbi_*; every number here is reproducible by re-running the section.
-- ============================================================================
\set ON_ERROR_STOP on
\pset pager off
\pset footer off
SET search_path = work, public;

\if :{?section}
\else
  \echo 'pass -v section=gap | reconcile'
  \quit
\endif

SELECT :'section' = 'gap' AS is_gap, :'section' = 'reconcile' AS is_rec \gset

-- the shipped scope (work.otbi_folder.ship — p3_otbi.sql §1b): what the release carries and what an
-- LLM pass would describe; the unshipped extension content is counted once, below the totals
DROP TABLE IF EXISTS pg_temp.shipped_col;
CREATE TEMP TABLE shipped_col AS
SELECT c.* FROM work.otbi_column c JOIN work.otbi_folder f ON f.subject_area = c.subject_area AND f.name = c.folder WHERE f.ship;
CREATE INDEX ON shipped_col (gap_cause);
DROP TABLE IF EXISTS pg_temp.shipped_folder;
CREATE TEMP TABLE shipped_folder AS SELECT * FROM work.otbi_folder WHERE ship;

\if :is_gap
\echo '# OTBI presentation catalog — gap list'
\echo ''
\echo 'Generated by `scripts/pipeline/p3_otbi.sh report` from `work.otbi_*` (no LLM run: descriptions come from'
\echo 'dictionary / view remarks reached through the DB bridge, or the referenced remarks of a derived expression).'
\echo 'A gap is a column or folder with NO description; `gap_cause` is the first reason that applies.'
\echo ''
\echo '## Totals'
\echo '```'
SELECT 'columns' AS entity, count(*) AS total, count(*) FILTER (WHERE description IS NOT NULL) AS described,
       count(*) FILTER (WHERE description IS NULL) AS gaps,
       round(100.0 * count(*) FILTER (WHERE description IS NOT NULL) / count(*), 1) AS pct_described
FROM   shipped_col
UNION ALL
SELECT 'folders', count(*), count(*) FILTER (WHERE description IS NOT NULL), count(*) FILTER (WHERE description IS NULL),
       round(100.0 * count(*) FILTER (WHERE description IS NOT NULL) / count(*), 1)
FROM   shipped_folder
UNION ALL
SELECT 'columns NOT shipped (extension content, see reconciliation)', count(*), count(*) FILTER (WHERE c.description IS NOT NULL), count(*) FILTER (WHERE c.description IS NULL),
       round(100.0 * count(*) FILTER (WHERE c.description IS NOT NULL) / count(*), 1)
FROM   work.otbi_column c JOIN work.otbi_folder f ON f.subject_area = c.subject_area AND f.name = c.folder WHERE NOT f.ship
UNION ALL
SELECT 'folders NOT shipped', count(*), count(*) FILTER (WHERE description IS NOT NULL), count(*) FILTER (WHERE description IS NULL),
       round(100.0 * count(*) FILTER (WHERE description IS NOT NULL) / count(*), 1)
FROM   work.otbi_folder WHERE NOT ship;
\echo '```'
\echo ''
\echo '## Columns without description, by cause'
\echo '```'
SELECT gap_cause, count(*) AS columns, count(DISTINCT subject_area) AS subject_areas,
       count(DISTINCT (subject_area, folder)) AS folders,
       count(*) FILTER (WHERE in_lineage) AS in_lineage, count(*) FILTER (WHERE in_crawl) AS in_crawl,
       count(*) FILTER (WHERE kind = 'measure') AS measures
FROM   shipped_col WHERE description IS NULL
GROUP  BY 1 ORDER BY 2 DESC;
\echo '```'
\echo 'Causes: no_probe = the folder was never probed (lineage-only folder, or a crawl folder the probe run did not'
\echo 'reach); failed_probe = the probe returned an nQSError / no status; empty_sql_folder = the probe succeeded but'
\echo 'OBIS returned no physical SQL (measure-only folders such as General Ledger - Balances Real Time "Balances");'
\echo 'alias_mismatch = the outer projection of the physical SQL does not have one alias per logical column;'
\echo 'unresolved_lineage = no DB column reached by the workbook, the alias resolution or the crawl;'
\echo 'derived_no_remarks = a physical expression whose referenced columns carry no remark;'
\echo 'ref_without_remark = a DB column is known but neither the dictionary nor the view-remark table describes it.'
\echo ''
\echo '## Dedupe estimate — how many DISTINCT things an LLM pass would have to describe'
\echo '```'
SELECT 'gap columns' AS what, count(*) AS rows FROM shipped_col WHERE description IS NULL
UNION ALL
SELECT 'distinct (column name) among gaps', count(DISTINCT name) FROM shipped_col WHERE description IS NULL
UNION ALL
SELECT 'distinct (column name, expression) among gaps', count(DISTINCT (name, coalesce(expression, ''))) FROM shipped_col WHERE description IS NULL
UNION ALL
SELECT 'distinct (column name, first db ref) among gaps', count(DISTINCT (name, coalesce(db_refs->0->>'t', '') || '.' || coalesce(db_refs->0->>'c', ''))) FROM shipped_col WHERE description IS NULL
UNION ALL
SELECT 'distinct physical expressions among derived gaps', count(DISTINCT expression) FROM shipped_col WHERE description IS NULL AND expression IS NOT NULL
UNION ALL
SELECT 'distinct (folder name) among gap folders', count(DISTINCT name) FROM shipped_folder WHERE description IS NULL
UNION ALL
SELECT 'distinct embedding texts (all columns)', count(*) FROM work.otbi_text WHERE kind = 'column';
\echo '```'
\echo ''
\echo '## Folders without description, by cause'
\echo '```'
SELECT CASE WHEN NOT in_corpus AND NOT in_crawl THEN 'lineage_only_no_unit'
            WHEN NOT in_corpus AND probe_status IS DISTINCT FROM 'Successful Completion' THEN 'failed_probe_no_unit'
            WHEN NOT in_corpus AND NOT coalesce(has_sql, false) THEN 'empty_sql_no_unit'
            WHEN NOT in_corpus THEN 'no_unit_other'
            ELSE 'unit_without_enrichment' END AS cause,
       count(*) AS folders, count(*) FILTER (WHERE kind = 'fact') AS fact_folders, count(*) FILTER (WHERE nested) AS nested_paths,
       sum(n_columns) AS columns
FROM   shipped_folder WHERE description IS NULL
GROUP  BY 1 ORDER BY 2 DESC;
\echo '```'
\echo ''
\echo '## Empty-SQL fact folders (probe succeeded, no physical SQL) — first 40 by column count'
\echo '```'
SELECT f.subject_area, f.name, f.n_columns
FROM   shipped_folder f WHERE f.has_sql = false AND f.probe_status = 'Successful Completion'
ORDER  BY f.n_columns DESC, 1, 2 LIMIT 40;
\echo '```'
\echo ''
\echo '## Failed probes, by nQSError family'
\echo '```'
SELECT coalesce(substring(status FROM '^\[nQSError: [0-9]+\]'), coalesce(status, '(null status)')) AS family, count(*) AS folders, sum(n_logical) AS columns
FROM   work.otbi_probe WHERE status IS DISTINCT FROM 'Successful Completion'
GROUP  BY 1 ORDER BY 2 DESC;
\echo '```'
\echo ''
\echo '## Gap columns per subject area — top 40'
\echo '```'
SELECT subject_area, count(*) AS gaps, count(*) FILTER (WHERE gap_cause = 'no_probe') AS no_probe,
       count(*) FILTER (WHERE gap_cause = 'ref_without_remark') AS ref_without_remark,
       count(*) FILTER (WHERE gap_cause = 'unresolved_lineage') AS unresolved,
       count(*) FILTER (WHERE gap_cause = 'derived_no_remarks') AS derived
FROM   shipped_col WHERE description IS NULL GROUP BY 1 ORDER BY 2 DESC LIMIT 40;
\echo '```'
\echo ''
\echo '## Description sources (what the no-LLM pass produced)'
\echo '```'
SELECT coalesce(desc_source, '(none)') AS desc_source, count(*) AS columns, count(*) FILTER (WHERE kind = 'measure') AS measures
FROM   shipped_col GROUP BY 1 ORDER BY 2 DESC;
\echo '```'
\endif

\if :is_rec
\echo '# OTBI presentation catalog — reconciliation (lineage workbooks vs SOAP crawl vs served corpus)'
\echo ''
\echo 'Generated by `scripts/pipeline/p3_otbi.sh report` from `work.otbi_*`. lineage = the six r13-26b workbooks;'
\echo 'crawl = metadata/subject_areas.json + the per-folder probes; corpus = an otbi unit titled `<SA>.<Folder>` in work.sql_unit.'
\echo ''
\echo '## Subject areas'
\echo '```'
SELECT count(*) AS total,
       count(*) FILTER (WHERE in_lineage AND in_crawl) AS in_both,
       count(*) FILTER (WHERE in_lineage AND NOT in_crawl) AS lineage_only,
       count(*) FILTER (WHERE NOT in_lineage AND in_crawl) AS crawl_only,
       count(*) FILTER (WHERE in_corpus) AS with_corpus_units,
       count(*) FILTER (WHERE pillar IS NULL) AS no_pillar
FROM   work.otbi_subject_area;
\echo '```'
\echo '### lineage-only subject areas'
\echo '```'
SELECT name, pillar, n_folders FROM work.otbi_subject_area WHERE in_lineage AND NOT in_crawl ORDER BY 1;
\echo '```'
\echo '### crawl-only subject areas'
\echo '```'
SELECT name, n_folders, n_columns, in_corpus FROM work.otbi_subject_area WHERE NOT in_lineage AND in_crawl ORDER BY 1;
\echo '```'
\echo '### subject areas with a lineage pillar only via the shared `OTBI Usage/Performance Real Time` rows'
\echo '```'
SELECT name, pillar FROM work.otbi_subject_area WHERE pillar LIKE '%,%' ORDER BY 1;
\echo '```'
\echo ''
\echo '## Ship scope (work.otbi_folder.ship — the rule in p3_otbi.sql §1b)'
\echo '```'
SELECT CASE WHEN ship THEN 'shipped' ELSE 'not shipped' END AS scope,
       CASE WHEN nested THEN 'crawl-only nested path (A > B > C)'
            WHEN subject_area LIKE 'custExt%' THEN 'custExt<uuid> subject area (App Composer custom object)'
            WHEN NOT in_lineage AND name ~* '\m(extension|custom attributes)\M' THEN 'crawl-only Extension / Custom Attributes folder'
            WHEN in_lineage THEN 'lineage folder'
            WHEN NOT EXISTS (SELECT 1 FROM work.otbi_folder l WHERE l.subject_area = f.subject_area AND l.in_lineage) THEN 'crawl-only flat folder of a subject area no workbook covers'
            ELSE 'crawl-only flat folder inside a workbook subject area (vendor folder the workbook does not map)' END AS class,
       count(*) AS folders, sum(n_columns) AS columns, count(*) FILTER (WHERE description IS NOT NULL) AS described_folders,
       count(*) FILTER (WHERE in_corpus) AS with_unit
FROM   work.otbi_folder f GROUP BY 1, 2 ORDER BY 1 DESC, 3 DESC;
\echo '```'
\echo '### shipped crawl-only flat folders inside workbook subject areas — top 30 by columns (the workbook under-documents these)'
\echo '```'
SELECT subject_area, name, n_columns, in_corpus
FROM   work.otbi_folder f
WHERE  ship AND NOT in_lineage
  AND  EXISTS (SELECT 1 FROM work.otbi_folder l WHERE l.subject_area = f.subject_area AND l.in_lineage)
ORDER  BY n_columns DESC, 1, 2 LIMIT 30;
\echo '```'
\echo '### NOT shipped Extension / Custom Attributes folders — top 20 by columns (the ruling to confirm)'
\echo '```'
SELECT subject_area, name, n_columns, in_corpus
FROM   work.otbi_folder f
WHERE  NOT ship AND NOT nested AND subject_area NOT LIKE 'custExt%'
ORDER  BY n_columns DESC, 1, 2 LIMIT 20;
\echo '```'
\echo ''
\echo '## Folders'
\echo '```'
SELECT count(*) AS total,
       count(*) FILTER (WHERE in_lineage AND in_crawl) AS in_both,
       count(*) FILTER (WHERE in_lineage AND NOT in_crawl) AS lineage_only,
       count(*) FILTER (WHERE NOT in_lineage AND in_crawl) AS crawl_only,
       count(*) FILTER (WHERE NOT in_lineage AND in_crawl AND nested) AS crawl_only_nested_paths,
       count(*) FILTER (WHERE in_corpus) AS with_unit,
       count(*) FILTER (WHERE in_lineage AND NOT in_corpus) AS lineage_without_unit,
       count(*) FILTER (WHERE in_corpus AND NOT in_lineage AND NOT in_crawl) AS corpus_only,
       count(*) FILTER (WHERE kind = 'fact') AS fact_folders,
       count(*) FILTER (WHERE kind = 'fact' AND kind_source = 'measures') AS fact_by_measures,
       count(*) FILTER (WHERE kind = 'fact' AND kind_source = 'name') AS fact_by_name
FROM   work.otbi_folder;
\echo '```'
\echo '### corpus units whose `<SA>.<Folder>` title matches no lineage/crawl folder'
\echo '```'
SELECT u.title, length(u.original_sql) AS sql_chars
FROM   work.sql_unit u
WHERE  u.source = 'otbi'
  AND  NOT EXISTS (SELECT 1 FROM work.otbi_folder f WHERE u.title = f.subject_area || '.' || f.name)
ORDER  BY 1 LIMIT 60;
\echo '```'
\echo '### lineage-only folders (in a workbook, not in the crawl) — first 60'
\echo '```'
SELECT subject_area, name, n_columns, in_corpus FROM work.otbi_folder WHERE in_lineage AND NOT in_crawl ORDER BY 1, 2 LIMIT 60;
\echo '```'
\echo '### crawl-only NON-nested folders (in the crawl, not in a workbook) — count per subject area, top 40'
\echo '```'
SELECT subject_area, count(*) AS folders, string_agg(name, ' | ' ORDER BY name) FILTER (WHERE rn <= 6) AS examples
FROM  (SELECT subject_area, name, row_number() OVER (PARTITION BY subject_area ORDER BY name) rn
       FROM work.otbi_folder WHERE NOT in_lineage AND in_crawl AND NOT nested) x
GROUP  BY 1 ORDER BY 2 DESC LIMIT 40;
\echo '```'
\echo ''
\echo '## Columns'
\echo '```'
SELECT count(*) AS total,
       count(*) FILTER (WHERE in_lineage AND in_crawl) AS in_both,
       count(*) FILTER (WHERE in_lineage AND NOT in_crawl) AS lineage_only,
       count(*) FILTER (WHERE NOT in_lineage AND in_crawl) AS crawl_only,
       count(*) FILTER (WHERE in_probe) AS in_probe,
       count(*) FILTER (WHERE data_type IS NOT NULL) AS with_data_type,
       count(*) FILTER (WHERE kind = 'measure') AS measures,
       count(*) FILTER (WHERE aggregation IS NOT NULL) AS with_aggregation,
       count(*) FILTER (WHERE expression IS NOT NULL) AS derived,
       count(*) FILTER (WHERE db_refs <> '[]') AS with_db_refs,
       count(*) FILTER (WHERE indexed) AS indexed,
       count(*) FILTER (WHERE description IS NOT NULL) AS described
FROM   work.otbi_column;
\echo '```'
\echo '### DB-ref agreement between the three sources (columns that have a ref from more than one)'
\echo '```'
WITH c AS (
  SELECT subject_area, folder, name,
         (SELECT jsonb_agg(e->>'t' || '.' || (e->>'c')) FROM jsonb_array_elements(db_refs) e WHERE e->'src' ? 'lineage') AS lin,
         (SELECT jsonb_agg(e->>'t' || '.' || (e->>'c')) FROM jsonb_array_elements(db_refs) e WHERE e->'src' ? 'probe') AS prb,
         (SELECT jsonb_agg(e->>'t' || '.' || (e->>'c')) FROM jsonb_array_elements(db_refs) e WHERE e->'src' ? 'crawl') AS crw
  FROM   work.otbi_column)
SELECT 'lineage vs probe' AS pair, count(*) FILTER (WHERE lin IS NOT NULL AND prb IS NOT NULL) AS both_present,
       count(*) FILTER (WHERE lin IS NOT NULL AND prb IS NOT NULL AND lin @> prb AND prb @> lin) AS agree,
       count(*) FILTER (WHERE lin IS NOT NULL AND prb IS NOT NULL AND (lin @> prb OR prb @> lin) AND NOT (lin @> prb AND prb @> lin)) AS subset,
       count(*) FILTER (WHERE lin IS NOT NULL AND prb IS NOT NULL AND NOT (lin @> prb OR prb @> lin)) AS disagree
FROM c
UNION ALL
SELECT 'probe vs crawl', count(*) FILTER (WHERE prb IS NOT NULL AND crw IS NOT NULL),
       count(*) FILTER (WHERE prb IS NOT NULL AND crw IS NOT NULL AND prb @> crw AND crw @> prb),
       count(*) FILTER (WHERE prb IS NOT NULL AND crw IS NOT NULL AND (prb @> crw OR crw @> prb) AND NOT (prb @> crw AND crw @> prb)),
       count(*) FILTER (WHERE prb IS NOT NULL AND crw IS NOT NULL AND NOT (prb @> crw OR crw @> prb))
FROM c
UNION ALL
SELECT 'lineage vs crawl', count(*) FILTER (WHERE lin IS NOT NULL AND crw IS NOT NULL),
       count(*) FILTER (WHERE lin IS NOT NULL AND crw IS NOT NULL AND lin @> crw AND crw @> lin),
       count(*) FILTER (WHERE lin IS NOT NULL AND crw IS NOT NULL AND (lin @> crw OR crw @> lin) AND NOT (lin @> crw AND crw @> lin)),
       count(*) FILTER (WHERE lin IS NOT NULL AND crw IS NOT NULL AND NOT (lin @> crw OR crw @> lin))
FROM c;
\echo '```'
\echo '### probe coverage'
\echo '```'
SELECT count(*) AS probed_folders, count(*) FILTER (WHERE status = 'Successful Completion') AS ok,
       count(*) FILTER (WHERE status = 'Successful Completion' AND has_sql) AS ok_with_sql,
       count(*) FILTER (WHERE status = 'Successful Completion' AND NOT has_sql) AS ok_no_sql,
       count(*) FILTER (WHERE status IS DISTINCT FROM 'Successful Completion') AS failed,
       count(*) FILTER (WHERE alias_mismatch) AS alias_mismatch,
       (SELECT count(*) FROM work.otbi_crawl_error) AS crawl_error_entries
FROM   work.otbi_probe;
\echo '```'
\echo '### the three verification subject areas — every lineage folder and whether a corpus unit exists'
\echo '```'
SELECT f.subject_area, f.name, f.kind, f.n_columns, f.in_lineage, f.in_crawl, f.in_corpus, f.has_sql, f.probe_status IS NOT DISTINCT FROM 'Successful Completion' AS probe_ok
FROM   work.otbi_folder f
WHERE  f.subject_area IN ('General Ledger - Balances Real Time', 'Payables Invoices - Transactions Real Time', 'Workforce Management - Worker Assignment Real Time')
ORDER  BY 1, 2;
\echo '```'
